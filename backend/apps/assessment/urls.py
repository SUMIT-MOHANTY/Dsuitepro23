"""
Assessment URLs for Enterprise LMS
Provides URL routing for Quiz, Question, QuizAttempt, Assignment, Submission, and Grade ViewSets.
"""

from django.urls import path, include
from rest_framework.routers import DefaultRouter

from apps.assessment.views import (
    QuizViewSet,
    QuestionViewSet,
    QuizAttemptViewSet,
    AssignmentViewSet,
    SubmissionViewSet,
    GradeViewSet,
    AssessmentDashboardView,
)

# Create router for assessment endpoints
router = DefaultRouter()

# Quiz endpoints
router.register(r'quizzes', QuizViewSet, basename='quiz')

# Question endpoints - nested under quizzes
# Questions can also be accessed directly at /questions/
router.register(r'questions', QuestionViewSet, basename='question')

# Quiz attempt endpoints
router.register(r'attempts', QuizAttemptViewSet, basename='quizattempt')

# Assignment endpoints
router.register(r'assignments', AssignmentViewSet, basename='assignment')

# Submission endpoints
router.register(r'submissions', SubmissionViewSet, basename='submission')

# Grade endpoints
router.register(r'grades', GradeViewSet, basename='grade')

urlpatterns = [
    # Include router URLs
    path('', include(router.urls)),
    
    # Assessment dashboard
    path('dashboard/', AssessmentDashboardView.as_view(), name='assessment-dashboard'),
]

# Custom action URLs are automatically generated by the router:
# - POST /quizzes/{id}/start/ - Start a quiz attempt
# - POST /quizzes/{id}/questions/ - Add question to quiz
# - POST /attempts/{id}/submit/ - Submit quiz answers
# - POST /attempts/{id}/grade/ - Grade a quiz attempt
# - POST /assignments/{id}/submit/ - Submit assignment
# - POST /submissions/{id}/grade/ - Grade a submission
# - GET /grades/user/{user_id}/ - Get user grades
